"""Export OpenAPI and TypeScript contracts from the same Pydantic/FastAPI schemas.

This generates contract artifacts only, not a frontend application.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

from .main import app

DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "contracts"


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(part) for part in schema[key])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object":
        if "properties" in schema:
            required = set(schema.get("required", []))
            fields = [f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(part)}" for name, part in schema["properties"].items()]
            return "{ " + "; ".join(fields) + " }"
        additional = schema.get("additionalProperties")
        return f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def typescript_contract(document: dict) -> str:
    lines = ["// Generated by python -m app.export_contracts. Do not edit manually.", "// Dates are RFC3339 strings; ratios are raw fractions, not percentages.", ""]
    for name, schema in sorted(document["components"]["schemas"].items()):
        if schema.get("type") == "object" and "properties" in schema:
            lines.append(f"export interface {name} {{")
            required = set(schema.get("required", []))
            for field, part in schema["properties"].items():
                optional = "" if field in required else "?"
                lines.append(f"  {json.dumps(field)}{optional}: {ts_type(part)};")
            lines.extend(["}", ""])
        else:
            lines.extend([f"export type {name} = {ts_type(schema)};", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Export API contract artifacts without initializing the DB or calling YouTube.")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    document = app.openapi()
    (args.out / "openapi.json").write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (args.out / "api.ts").write_text(typescript_contract(document), encoding="utf-8")
    print("Exported openapi.json and api.ts")


if __name__ == "__main__":
    main()
